-- Manual syntax highlighting check: NZPLSQL and Netezza DDL keywords.

-- EXPECT: CREATE TABLE, data types, DISTRIBUTE ON, ORGANIZE ON are live-colored.
-- EXPECT: The first JUST_DATA below stays database-blue even though a procedure follows.
CREATE TABLE JUST_DATA.ADMIN.COLOR_CHECK_FACT (
  ID INT NOT NULL,
  ACCOUNTKEY INT8,
  STATUS NVARCHAR(20),
  CREATED_AT TIMESTAMPTZ
)
DISTRIBUTE ON (ACCOUNTKEY)
ORGANIZE ON (CREATED_AT);

-- EXPECT: maintenance and DDL commands are live-colored.
GROOM TABLE JUST_DATA.ADMIN.COLOR_CHECK_FACT RECORDS ALL;
GENERATE EXPRESS STATISTICS ON JUST_DATA.ADMIN.COLOR_CHECK_FACT;
CREATE MATERIALIZED VIEW ADMIN.COLOR_CHECK_MV AS
SELECT ACCOUNTKEY, COUNT(*) AS CNT
FROM JUST_DATA.ADMIN.COLOR_CHECK_FACT
GROUP BY ACCOUNTKEY;

-- EXPECT: CALL/EXEC/EXECUTE are live-colored outside comments.
CALL JUST_DATA..SP_REFRESH_COLOR_CHECK();
EXEC JUST_DATA..SP_REFRESH_COLOR_CHECK();

-- EXPECT: NZPLSQL keywords are live-colored in procedure text.
CREATE OR REPLACE PROCEDURE ADMIN.SP_COLOR_CHECK(IN p_account INT, OUT p_count INT)
RETURNS INT
LANGUAGE NZPLSQL
EXECUTE AS OWNER
AS BEGIN_PROC
DECLARE
  v_sql VARCHAR(2000);
BEGIN
  v_sql := 'SELECT COUNT(*) FROM JUST_DATA.ADMIN.COLOR_CHECK_FACT';
  EXECUTE IMMEDIATE v_sql;
  RAISE NOTICE 'color check ran';
  RETURN 1;
EXCEPTION
  WHEN OTHERS THEN
    RAISE NOTICE 'color check failed';
    RETURN 0;
END;
END_PROC;

